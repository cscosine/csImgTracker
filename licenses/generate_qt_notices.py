#!/usr/bin/env python3
"""Write Qt-third-party-notices.md: the third-party code inside the Qt libraries and plugins of the deployments.

The source is the SBOM of the Qt packages (SPDX tag-value files, <Qt>/sbom/<repository>-<version>.spdx), one Qt
package per platform, because Qt bundles different libraries per platform (e.g. HarfBuzz and FreeType on Windows and
macOS, the system ones on Linux):

    ./generate_qt_notices.py linux:<qt>/sbom/qtbase-6.12.0.spdx linux:<qt>/sbom/qtwayland-6.12.0.spdx \
        windows:<qt>/sbom/qtbase-6.12.0.spdx macos:<qt>/sbom/qtbase-6.12.0.spdx

Kept: the attributions of the Qt modules shipped (SHIPPED_MODULES) and of the platform, style and Wayland plugins
(SHIPPED_PLUGINS), and the libraries Qt bundles (Bundled*). It also writes the texts of the LicenseRef-* licenses (in
the SBOM) to texts/, and prints the SPDX license identifiers used, whose texts go to texts/<id>.txt.
"""

import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

# the Qt modules the deployments ship (their libraries)
SHIPPED_MODULES = {
    "Core",
    "Gui",
    "Widgets",
    "OpenGL",
    "OpenGLWidgets",
    "DBus",
    "XcbQpaPrivate",
    "WaylandClient",
}
# the plugins the deployments ship: platform integrations, styles, Wayland shells and decorations
SHIPPED_PLUGINS = re.compile(r"^Q(Xcb|Wayland|Windows|ModernWindows|Cocoa|MacStyle|Offscreen)\w*Plugin$")
NOT_SHIPPED_PLUGINS = re.compile(r"Direct2D|FullScreenShell|IviShell")


@dataclass
class Component:
    name: str
    version: str
    license: str
    copyright: str
    used_by: set[str] = field(default_factory=set)
    platforms: set[str] = field(default_factory=set)


def field_value(block: str, key: str) -> str:
    m = re.search(rf"^{key}: (.*)$", block, re.M)
    return m.group(1).strip() if m else ""


def text_value(block: str, key: str) -> str:
    m = re.search(rf"^{key}: <text>(.*?)</text>", block, re.M | re.S)
    return m.group(1).strip() if m else field_value(block, key)


def license_ids(expression: str) -> set[str]:
    return {t for t in re.split(r"[\s()]+", expression) if t and t not in ("AND", "OR", "WITH", "NOASSERTION", "NONE")}


def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 2
    components: dict[tuple[str, str, str], Component] = {}
    extracted: dict[str, str] = {}
    qt_version = ""
    for arg in argv:
        platform, _, path = arg.partition(":")
        text = Path(path).read_text(encoding="utf-8")
        for block in re.split(r"\n(?=LicenseID: )", text):
            if block.startswith("LicenseID: LicenseRef-"):
                extracted[field_value(block, "LicenseID")] = text_value(block, "ExtractedText")
        for block in re.split(r"\n(?=PackageName: )", text):
            if not block.startswith("PackageName: "):
                continue
            name = field_value(block, "PackageName")
            if name == "Core":
                qt_version = field_value(block, "PackageVersion")
            if "_Attribution_" in name:
                owner, _, library = name.partition("_Attribution_")
                keep = owner in SHIPPED_MODULES or (
                    SHIPPED_PLUGINS.match(owner) is not None and NOT_SHIPPED_PLUGINS.search(owner) is None
                )
            elif name.startswith("Bundled"):
                owner, library, keep = "Qt (bundled)", name.removeprefix("Bundled"), True
            else:
                keep = False
            if not keep:
                continue
            version = field_value(block, "PackageVersion") or "unknown"
            lic = field_value(block, "PackageLicenseConcluded") or field_value(block, "PackageLicenseDeclared")
            key = (library.lower(), version, lic)
            c = components.setdefault(key, Component(library, version, lic, text_value(block, "PackageCopyrightText")))
            c.used_by.add(owner)
            c.platforms.add(platform)

    all_platforms = {a.partition(":")[0] for a in argv}
    ids: set[str] = set()
    out = [
        f"# Qt {qt_version}: third-party code",
        "",
        "The Qt libraries and plugins of the deployments (LGPL-3.0, see",
        "[THIRD-PARTY-NOTICES.md](THIRD-PARTY-NOTICES.md)) contain the following third-party code. Generated by",
        "`generate_qt_notices.py` from the SBOM of the Qt packages (csqt6), for the Qt modules and plugins the",
        "deployments ship; the license texts are in `texts/`.",
        "",
    ]
    for c in sorted(components.values(), key=lambda c: (c.name.lower(), c.version)):
        ids |= license_ids(c.license)
        where = "all" if c.platforms == all_platforms else ", ".join(sorted(c.platforms))
        out += [
            f"## {c.name} {c.version}",
            "",
            f"- License: {c.license}",
            f"- In: {', '.join(sorted(c.used_by))}; platforms: {where}",
            "",
            "```text",
            c.copyright,
            "```",
            "",
        ]
    texts = Path(__file__).resolve().parent / "texts"
    texts.mkdir(exist_ok=True)
    for lic_id in sorted(i for i in ids if i.startswith("LicenseRef-")):
        if lic_id in extracted:
            (texts / f"{lic_id}.txt").write_text(extracted[lic_id] + "\n", encoding="utf-8")
    Path(__file__).resolve().with_name("Qt-third-party-notices.md").write_text("\n".join(out), encoding="utf-8")
    print("license identifiers:", " ".join(sorted(ids)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
